window.NepaliDateEngine = {
  getMonthDays: function(bsYear, bsMonth) {
    if (BS_CALENDAR_DATA[bsYear] && BS_CALENDAR_DATA[bsYear][bsMonth - 1]) {
      return BS_CALENDAR_DATA[bsYear][bsMonth - 1];
    }
    return 30;
  },

  getBsDayOfWeek: function(bsYear, bsMonth, bsDay) {
    const mm = String(bsMonth).padStart(2, '0');
    const dd = String(bsDay).padStart(2, '0');
    const adStr = this.bsToAd(`${bsYear}-${mm}-${dd}`);
    if (!adStr) return 0;
    const parts = adStr.split('-').map(Number);
    const d = new Date(Date.UTC(parts[0], parts[1] - 1, parts[2]));
    return d.getUTCDay(); // 0 = Sunday, 6 = Saturday
  },

  adToBs: function(adDateStr) {
    if (!adDateStr) return "";
    const parts = adDateStr.split('-').map(Number);
    const targetDate = new Date(Date.UTC(parts[0], parts[1] - 1, parts[2]));
    const anchorDate = new Date(Date.UTC(1943, 3, 14));

    let daysDiff = Math.floor((targetDate - anchorDate) / (1000 * 60 * 60 * 24));
    if (daysDiff < 0) return "";

    let bsYear = NEPALI_DATE_ANCHOR_BS_YEAR;
    let bsMonth = 1;
    let bsDay = 1;

    while (daysDiff > 0) {
      if (!BS_CALENDAR_DATA[bsYear]) break;
      const yearDays = BS_CALENDAR_DATA[bsYear].reduce((a, b) => a + b, 0);

      if (daysDiff >= yearDays) {
        daysDiff -= yearDays;
        bsYear++;
      } else {
        const months = BS_CALENDAR_DATA[bsYear];
        for (let m = 0; m < 12; m++) {
          if (daysDiff >= months[m]) {
            daysDiff -= months[m];
          } else {
            bsMonth = m + 1;
            bsDay = daysDiff + 1;
            daysDiff = 0;
            break;
          }
        }
      }
    }

    const mm = String(bsMonth).padStart(2, '0');
    const dd = String(bsDay).padStart(2, '0');
    return `${bsYear}-${mm}-${dd}`;
  },

  bsToAd: function(bsDateStr) {
    if (!bsDateStr) return "";
    const parts = bsDateStr.split('-').map(Number);
    if (parts.length !== 3 || isNaN(parts[0]) || isNaN(parts[1]) || isNaN(parts[2])) {
      return null;
    }

    const bsYear = parts[0];
    const bsMonth = parts[1];
    const bsDay = parts[2];

    if (!BS_CALENDAR_DATA[bsYear]) return null;
    if (bsMonth < 1 || bsMonth > 12) return null;

    const maxDays = BS_CALENDAR_DATA[bsYear][bsMonth - 1];
    if (bsDay < 1 || bsDay > maxDays) return null;

    let totalDays = 0;
    for (let y = NEPALI_DATE_ANCHOR_BS_YEAR; y < bsYear; y++) {
      totalDays += BS_CALENDAR_DATA[y].reduce((a, b) => a + b, 0);
    }
    for (let m = 1; m < bsMonth; m++) {
      totalDays += BS_CALENDAR_DATA[bsYear][m - 1];
    }
    totalDays += (bsDay - 1);

    const anchorDate = new Date(Date.UTC(1943, 3, 14));
    const targetDate = new Date(anchorDate.getTime() + totalDays * (1000 * 60 * 60 * 24));

    const yyyy = targetDate.getUTCFullYear();
    const mm = String(targetDate.getUTCMonth() + 1).padStart(2, '0');
    const dd = String(targetDate.getUTCDate()).padStart(2, '0');
    return `${yyyy}-${mm}-${dd}`;
  }
};