def ad_to_bs(ad_date):
    """Converts a datetime.date (AD) to a string 'YYYY-MM-DD' (BS)."""
    if isinstance(ad_date, str):
        ad_date = datetime.datetime.strptime(ad_date, "%Y-%m-%d").date()

    if ad_date < ANCHOR_AD_DATE:
        raise ValueError("Date is prior to supported range (before 2000 BS).")

    days_diff = (ad_date - ANCHOR_AD_DATE).days

    bs_year = ANCHOR_BS_YEAR
    bs_month = 1
    bs_day = 1

    while days_diff > 0:
        year_days = sum(BS_CALENDAR_DATA[bs_year])
        if days_diff >= year_days:
            days_diff -= year_days
            bs_year += 1
            if bs_year not in BS_CALENDAR_DATA:
                raise ValueError("Date exceeds supported calendar range.")
        else:
            for month_idx, m_days in enumerate(BS_CALENDAR_DATA[bs_year]):
                if days_diff >= m_days:
                    days_diff -= m_days
                else:
                    bs_month = month_idx + 1
                    bs_day = days_diff + 1
                    days_diff = 0
                    break

    return f"{bs_year:04d}-{bs_month:02d}-{bs_day:02d}"


def bs_to_ad(bs_date_str):
    """Converts a BS date string 'YYYY-MM-DD' to datetime.date (AD)."""
    parts = [int(p) for p in bs_date_str.strip().split("-")]
    if len(parts) != 3:
        raise ValueError("Invalid BS date format. Use YYYY-MM-DD.")

    bs_year, bs_month, bs_day = parts

    if bs_year not in BS_CALENDAR_DATA:
        raise ValueError(f"BS Year {bs_year} is out of supported range (2000-2095).")
    if bs_month < 1 or bs_month > 12:
        raise ValueError("Invalid BS Month (1-12).")

    max_days = BS_CALENDAR_DATA[bs_year][bs_month - 1]
    if bs_day < 1 or bs_day > max_days:
        raise ValueError(f"Invalid BS Day for {bs_year}-{bs_month:02d}. Month has {max_days} days.")

    total_days = 0

    # Add days for completed years
    for y in range(ANCHOR_BS_YEAR, bs_year):
        total_days += sum(BS_CALENDAR_DATA[y])

    # Add days for completed months in current year
    for m in range(1, bs_month):
        total_days += BS_CALENDAR_DATA[bs_year][m - 1]

    # Add days in current month
    total_days += (bs_day - 1)

    return ANCHOR_AD_DATE + datetime.timedelta(days=total_days)